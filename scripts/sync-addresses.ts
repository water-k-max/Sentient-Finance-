import * as fs from "fs";
import * as path from "path";

/**
 * sync-addresses.ts — Post-deploy utility
 *
 * Reads deployed-addresses.json (the canonical source written by deploy.ts)
 * and writes identically-formatted exports to both:
 *   - scripts/addresses.ts    (hardhat scripts)
 *   - frontend/src/config/addresses.ts  (Vite frontend)
 *
 * Usage:
 *   npx hardhat run scripts/sync-addresses.ts
 *
 * Or as part of post-deploy:
 *   npx hardhat run scripts/deploy.ts --network somnia && npx hardhat run scripts/sync-addresses.ts
 */

const ROOT = path.resolve(__dirname, "..");
const SRC_JSON = path.join(ROOT, "deployed-addresses.json");
const DEST_SCRIPT = path.join(ROOT, "scripts", "addresses.ts");
const DEST_FRONTEND = path.join(ROOT, "frontend", "src", "config", "addresses.ts");

type AddressMap = Record<string, string | Record<string, string>>;

function formatValue(v: string | Record<string, string>, indent: string): string {
  if (typeof v === "string") {
    return `${indent}"${v}"`;
  }
  // Nested object (e.g. orderBooks)
  const keys = Object.keys(v);
  const inner = keys.map((k) => `${indent}    "${k}": "${v[k]}"`).join(",\n");
  return `${indent}{\n${inner}\n${indent}}`;
}

function generateTs(data: AddressMap): string {
  const keys = Object.keys(data);
  const lines = keys.map((k, i) => {
    const comma = i < keys.length - 1 ? "," : "";
    return `  "${k}": ${formatValue(data[k], "")}${comma}`;
  });
  return `// Auto-generated by scripts/sync-addresses.ts — DO NOT EDIT MANUALLY
// Source: deployed-addresses.json

export const CONTRACT_ADDRESSES: Record<string, any> = {
${lines.join("\n")}
};

export const SOMNIA_CHAIN_ID = 50312;
export const SOMNIA_RPC_URL = "https://dream-rpc.somnia.network";
`;
}

function generateFrontendTs(data: AddressMap): string {
  const keys = Object.keys(data);
  const lines = keys.map((k, i) => {
    const comma = i < keys.length - 1 ? "," : "";
    return `  "${k}": ${formatValue(data[k], "")}${comma}`;
  });
  return `// Auto-generated by scripts/sync-addresses.ts — DO NOT EDIT MANUALLY
// Source: deployed-addresses.json

export const CONTRACT_ADDRESSES: Record<string, any> = {
${lines.join("\n")}
};

export const SOMNIA_CHAIN_ID = 50312;
export const SOMNIA_RPC_URL = "https://dream-rpc.somnia.network";

export function isDeployed(): boolean {
  return CONTRACT_ADDRESSES.marginVault !== "0x0000000000000000000000000000000000000000";
}
`;
}

function main() {
  if (!fs.existsSync(SRC_JSON)) {
    console.error(`❌ ${SRC_JSON} not found — run scripts/deploy.ts first`);
    process.exit(1);
  }

  const raw = fs.readFileSync(SRC_JSON, "utf-8");
  const data: AddressMap = JSON.parse(raw);

  // Validate required keys
  const required = ["mockUSDC", "marginVault", "orderBookFactory", "orderBooks"];
  for (const key of required) {
    if (!(key in data)) {
      console.error(`❌ Missing key "${key}" in ${SRC_JSON}`);
      process.exit(1);
    }
  }

  // Write scripts/addresses.ts
  const scriptTs = generateTs(data);
  fs.writeFileSync(DEST_SCRIPT, scriptTs, "utf-8");
  console.log(`✅ ${DEST_SCRIPT}`);

  // Write frontend/src/config/addresses.ts
  const frontendTs = generateFrontendTs(data);
  fs.writeFileSync(DEST_FRONTEND, frontendTs, "utf-8");
  console.log(`✅ ${DEST_FRONTEND}`);

  console.log("\n📋 Addresses synced from deployed-addresses.json to both targets.");
}

main();
