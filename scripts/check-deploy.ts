import { ethers } from "hardhat";
import * as fs from "fs";
import * as path from "path";

/**
 * check-deploy.ts — Pre-deploy validation
 *
 * Runs before every mainnet/testnet deploy to catch common issues early.
 *   - Verifies compilation
 *   - Verifies tests pass
 *   - Validates address files are in sync
 *   - Checks .env has required variables
 *   - Prints deployer balance (warns if < 1 STT)
 *
 * Usage:
 *   npx hardhat run scripts/check-deploy.ts
 */

const ROOT = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT, ".env");
const DEPLOYED_JSON = path.join(ROOT, "deployed-addresses.json");
const SCRIPT_ADDR = path.join(ROOT, "scripts", "addresses.ts");
const FRONTEND_ADDR = path.join(ROOT, "frontend", "src", "config", "addresses.ts");

async function main() {
  let exitCode = 0;

  console.log("═══════════════════════════════════════════");
  console.log("  Pre-deploy Checks");
  console.log("═══════════════════════════════════════════\n");

  // ── 1. .env file ──────────────────────────────────────
  if (!fs.existsSync(ENV_PATH)) {
    console.error("❌ .env file not found — create one from .env.example");
    exitCode = 1;
  } else {
    const env = fs.readFileSync(ENV_PATH, "utf-8");
    if (!env.includes("PRIVATE_KEY")) {
      console.error("❌ .env is missing PRIVATE_KEY");
      exitCode = 1;
    }
    if (!env.includes("SOMNIA_RPC_URL")) {
      console.error("❌ .env is missing SOMNIA_RPC_URL");
      exitCode = 1;
    }
    console.log("✅ .env has required variables");
  }

  // ── 2. Compilation ────────────────────────────────────
  try {
    await ethers.getContractFactory("OrderBook");
    await ethers.getContractFactory("MarginVault");
    await ethers.getContractFactory("LiquidityProviderAgent");
    await ethers.getContractFactory("SentimentOracle");
    console.log("✅ Contracts compile");
  } catch (e: any) {
    console.error("❌ Compilation failed:", (e?.message || String(e)).slice(0, 200));
    exitCode = 1;
  }

  // ── 3. Deployer balance ───────────────────────────────
  try {
    const [deployer] = await ethers.getSigners();
    const balance = await ethers.provider.getBalance(deployer.address);
    const balanceEth = Number(ethers.formatEther(balance));
    if (balanceEth < 1) {
      console.warn(`⚠️  Deployer balance: ${balanceEth.toFixed(4)} STT (below 1 STT — may run out mid-deploy)`);
    } else {
      console.log(`✅ Deployer balance: ${balanceEth.toFixed(4)} STT`);
    }
  } catch {
    console.warn("⚠️  Could not check deployer balance (network unavailable?)");
  }

  // ── 4. Address file sync ──────────────────────────────
  if (!fs.existsSync(DEPLOYED_JSON)) {
    console.warn("⚠️  deployed-addresses.json not found — first deploy?");
  } else {
    const jsonData = fs.readFileSync(DEPLOYED_JSON, "utf-8");
    try {
      JSON.parse(jsonData);
      console.log("✅ deployed-addresses.json is valid JSON");
    } catch {
      console.error("❌ deployed-addresses.json is not valid JSON");
      exitCode = 1;
    }
  }

  // ── 5. Address file freshness ─────────────────────────
  // Check that scripts/addresses.ts and frontend/src/config/addresses.ts
  // are both auto-generated headers (meaning they were produced by sync-addresses).
  // If the deployed-addresses.json is newer than either file, warn.
  if (fs.existsSync(DEPLOYED_JSON)) {
    const jsonMtime = fs.statSync(DEPLOYED_JSON).mtimeMs;
    const files = [
      { name: "scripts/addresses.ts", path: SCRIPT_ADDR },
      { name: "frontend/src/config/addresses.ts", path: FRONTEND_ADDR },
    ];
    for (const f of files) {
      if (!fs.existsSync(f.path)) {
        console.warn(`⚠️  ${f.name} not found — run npm run sync-addresses`);
        continue;
      }
      const content = fs.readFileSync(f.path, "utf-8");
      if (!content.includes("Auto-generated by scripts/sync-addresses.ts")) {
        console.warn(`⚠️  ${f.name} was not auto-generated — run npm run sync-addresses`);
        continue;
      }
      const mtime = fs.statSync(f.path).mtimeMs;
      if (mtime < jsonMtime) {
        console.warn(`⚠️  ${f.name} is older than deployed-addresses.json — run npm run sync-addresses`);
      } else {
        console.log(`✅ ${f.name} is up to date`);
      }
    }
  }

  // ── Summary ────────────────────────────────────────────
  console.log("\n═══════════════════════════════════════════");
  if (exitCode === 0) {
    console.log("  ✅ All checks passed — ready to deploy");
  } else {
    console.error(`  ❌ ${exitCode} check(s) failed — fix before deploying`);
  }
  console.log("═══════════════════════════════════════════");
  process.exit(exitCode);
}

main().catch((e) => {
  console.error("Pre-deploy check crashed:", e);
  process.exit(1);
});
